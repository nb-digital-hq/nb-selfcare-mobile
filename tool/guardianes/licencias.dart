import 'dart:io';

import 'comun.dart';

// Todo lo que se distribuye dentro de la app debe ser compatible con Apache-2.0
// y abierto: nada GPL/AGPL/LGPL ni componentes propietarios. Este guardián
// clasifica la licencia de cada paquete del pubspec.lock y, con `--escribir`,
// regenera THIRD-PARTY-NOTICES.md; sin él, comprueba que esté al día.
const Map<String, String> _firmas = <String, String>{
  'GNU AFFERO GENERAL PUBLIC': 'AGPL',
  'GNU LESSER GENERAL PUBLIC': 'LGPL',
  'GNU GENERAL PUBLIC': 'GPL',
  'Server Side Public License': 'SSPL',
  'Mozilla Public License': 'MPL-2.0',
  'Apache License': 'Apache-2.0',
  'Permission is hereby granted, free of charge': 'MIT',
  'Redistribution and use in source and binary forms': 'BSD',
  'Permission to use, copy, modify, and/or distribute': 'ISC',
  'zlib License': 'Zlib',
};
const Set<String> _permitidas = <String>{'Apache-2.0', 'MIT', 'BSD', 'ISC', 'Zlib'};

// Excepciones con su motivo: paquetes que el pubspec.lock resuelve pero que
// no se compilan en ninguna plataforma que se distribuye (Android e iOS). Si
// un día lo hicieran, MPL-2.0 es copyleft por archivo y sigue siendo
// compatible con Apache-2.0. Ver docs/legal/third-party-notices.md.
const Map<String, String> _excepciones = <String, String>{
  'bluez': 'solo Linux (transitiva de universal_ble)',
  'dbus': 'solo Linux (transitiva de universal_ble)',
};

String _cachePub() {
  final String? env = Platform.environment['PUB_CACHE'];
  if (env != null && env.isNotEmpty) {
    return env;
  }
  final String home = Platform.environment['HOME'] ?? Platform.environment['LOCALAPPDATA'] ?? '';
  return Platform.isWindows ? '$home\\Pub\\Cache' : '$home/.pub-cache';
}

void main(List<String> args) {
  final Informe inf = Informe('licencias');
  final List<String> lock = File('pubspec.lock').readAsLinesSync();
  final List<(String, String, String, String)> paquetes = <(String, String, String, String)>[];
  String? nombre;
  String? fuente;
  String? version;
  String? dependencia;
  void volcar() {
    if (nombre != null && fuente == 'hosted' && version != null) {
      paquetes.add((nombre, version, dependencia ?? '', ''));
    }
  }

  for (final String l in lock) {
    final RegExpMatch? p = RegExp(r'^  ([a-z0-9_]+):$').firstMatch(l);
    if (p != null) {
      volcar();
      nombre = p.group(1);
      fuente = null;
      version = null;
      dependencia = null;
      continue;
    }
    final RegExpMatch? s = RegExp(r'^    source: (\w+)').firstMatch(l);
    if (s != null) fuente = s.group(1);
    final RegExpMatch? v = RegExp(r'^    version: "([^"]+)"').firstMatch(l);
    if (v != null) version = v.group(1);
    final RegExpMatch? d = RegExp(r'^    dependency: "?([^"]+)"?').firstMatch(l);
    if (d != null) dependencia = d.group(1);
  }
  volcar();

  final StringBuffer avisos = StringBuffer()
    ..writeln('# Third-party notices')
    ..writeln()
    ..writeln(
      'NB SelfCare Mobile includes the following third-party packages. Each one keeps its own licence;',
    )
    ..writeln('the full text of every licence follows its entry. This file is generated by')
    ..writeln('`dart run tool/guardianes/licencias.dart --escribir` from `pubspec.lock`.')
    ..writeln()
    ..writeln('Fonts bundled in `assets/fonts/` (Manrope and Space Grotesk) are licensed under the')
    ..writeln(
      'SIL Open Font License 1.1. Flutter and its SDK packages are licensed under the BSD 3-Clause',
    )
    ..writeln(
      'licence. Native libraries brought in by these packages (AndroidX, CameraX, zxing-cpp, SQLite)',
    )
    ..writeln('are covered by the licences listed with each package.')
    ..writeln()
    ..writeln('The full text of the SIL Open Font License and the font copyright notices are in')
    ..writeln('`assets/fonts/OFL.txt`.')
    ..writeln()
    ..writeln(
      'Food data: the offline food catalogue is derived from USDA FoodData Central (public domain,',
    )
    ..writeln(
      'U.S. Department of Agriculture). Products looked up on demand come from Open Food Facts and',
    )
    ..writeln(
      'are available under the Open Database License (ODbL); see https://world.openfoodfacts.org.',
    )
    ..writeln();
  final String raiz = '${_cachePub()}/hosted/pub.dev';
  for (final (String n, String ver, String dep, String _) in paquetes) {
    if (dep == 'direct dev') {
      continue; // herramientas de desarrollo: no se distribuyen
    }
    final Directory dir = Directory('$raiz/$n-$ver');
    if (!dir.existsSync()) {
      inf.fallo('pubspec.lock', '$n $ver no está en la caché de pub (ejecuta flutter pub get)');
      continue;
    }
    final List<File> lic = dir
        .listSync()
        .whereType<File>()
        .where(
          (File f) => RegExp(
            r'^(LICEN[CS]E|COPYING)',
            caseSensitive: false,
          ).hasMatch(f.uri.pathSegments.last),
        )
        .toList();
    // El orden de listSync depende del sistema de archivos: se ordena para que
    // el aviso generado sea el mismo en cualquier máquina.
    lic.sort((File a, File b) => a.path.compareTo(b.path));
    if (lic.isEmpty) {
      inf.fallo(n, 'sin archivo de licencia');
      continue;
    }
    final String texto = lic.first
        .readAsStringSync()
        .replaceAll('\r\n', '\n')
        .replaceAll('\r', '\n');
    String tipo = 'desconocida';
    for (final MapEntry<String, String> e in _firmas.entries) {
      if (texto.toLowerCase().contains(e.key.toLowerCase())) {
        tipo = e.value;
        break;
      }
    }
    if (!_permitidas.contains(tipo) && !_excepciones.containsKey(n)) {
      inf.fallo(n, 'licencia no admitida: $tipo');
    }
    avisos
      ..writeln('## $n $ver ($tipo)')
      ..writeln()
      ..writeln('```text')
      ..writeln(texto.trim())
      ..writeln('```')
      ..writeln();
  }
  final File destino = File('THIRD-PARTY-NOTICES.md');
  final String nuevo = avisos.toString();
  if (args.contains('--escribir')) {
    destino.writeAsStringSync(nuevo);
  } else if (!destino.existsSync() || destino.readAsStringSync() != nuevo) {
    final List<String> viejo = destino.existsSync() ? destino.readAsLinesSync() : <String>[];
    final List<String> lineas = nuevo.split('\n');
    for (int i = 0; i < lineas.length; i++) {
      if (i >= viejo.length || viejo[i] != lineas[i]) {
        stderr.writeln('primera diferencia en la línea ${i + 1}: ${lineas[i]}');
        break;
      }
    }
    inf.fallo(
      'THIRD-PARTY-NOTICES.md',
      'desactualizado (dart run tool/guardianes/licencias.dart --escribir)',
    );
  }
  exit(inf.cerrar());
}
