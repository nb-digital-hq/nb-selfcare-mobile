/// [es] en [idioma] según [tabla]; sin traducción, se queda en español.
String traducirSemilla(Map<String, ({String en, String pt})> tabla, String es, String idioma) {
  final ({String en, String pt})? t = tabla[es];
  if (t == null) return es;
  return switch (idioma) {
    'en' => t.en,
    'pt' => t.pt,
    _ => es,
  };
}
